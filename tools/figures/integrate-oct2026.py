#!/usr/bin/env python3
"""One-off: adds the Oct 2026 programme figures to the three Figures pages.
Edits: lead paragraph, three new gallery sections, JSON-LD (numberOfItems,
ListItems 16-25, hasPart +10). Run from the repo root. Kept for the record."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
ALTS = json.load(open(os.path.join(HERE, 'alts-oct2026.json'), encoding='utf-8'))

PAGES = {
    'fr': dict(file='figures.html', reuse='/reutilisation-figures', date='20 oct. 2026'),
    'en': dict(file='en/figures.html', reuse='/en/figure-reuse', date='20 Oct 2026'),
    'es': dict(file='es/figuras.html', reuse='/es/reutilizacion-figuras', date='20 oct. 2026'),
}

LEAD = {
    'fr': ("Les figures originales publiées avec mes articles sur l’intelligence artificielle en éducation, réunies sur une page.",
           "Les figures originales publiées sur ce site — avec mes articles sur l’intelligence artificielle en éducation et sur mes pages de recherche et de formation — réunies sur une page."),
    'en': ("The original figures published with my articles on artificial intelligence in education, gathered on one page.",
           "The original figures published on this site — with my articles on artificial intelligence in education and on my research and training pages — gathered on one page."),
    'es': ("Las figuras originales publicadas con mis artículos sobre inteligencia artificial en educación, reunidas en una página.",
           "Las figuras originales publicadas en este sitio — con mis artículos sobre inteligencia artificial en educación y en mis páginas de investigación y formación — reunidas en una página."),
}

SECTIONS = {
    'fr': [('Programme de recherche', '/recherche',
            ['chercheur-ia-education', 'programme-recherche', 'recherche-items-llm',
             'recherche-essai-grappes', 'acceptation-modele-tam', 'methodes-recherche']),
           ('L’IA dans les textes romands', '/ia-ecole-romandie',
            ['politiques-niveaux', 'politiques-corpus-wpr', 'ia-classe-quatre-questions']),
           ('Formations', '/formations', ['formations-formats'])],
    'en': [('Research programme', '/en/research',
            ['chercheur-ia-education', 'programme-recherche', 'recherche-items-llm',
             'recherche-essai-grappes', 'acceptation-modele-tam', 'methodes-recherche']),
           ('AI in the Swiss texts', '/en/ai-schools-french-speaking-switzerland',
            ['politiques-niveaux', 'politiques-corpus-wpr', 'ia-classe-quatre-questions']),
           ('Training', '/en/training', ['formations-formats'])],
    'es': [('Programa de investigación', '/es/investigacion',
            ['chercheur-ia-education', 'programme-recherche', 'recherche-items-llm',
             'recherche-essai-grappes', 'acceptation-modele-tam', 'methodes-recherche']),
           ('La IA en los textos suizos', '/es/ia-escuela-suiza-romanda',
            ['politiques-niveaux', 'politiques-corpus-wpr', 'ia-classe-quatre-questions']),
           ('Formaciones', '/es/formaciones', ['formations-formats'])],
}

CAPTIONS = {
    'chercheur-ia-education': dict(
        fr='Enseignant et chercheur en éducation dans le canton de Vaud : trois axes de travail.',
        en='Teacher and education researcher in the canton of Vaud: three strands of work.',
        es='Docente e investigador en educación en el cantón de Vaud: tres ejes de trabajo.'),
    'programme-recherche': dict(
        fr='Le programme de recherche en trois axes : évaluation, acceptation, politiques.',
        en='The research programme in three strands: assessment, acceptance, policy.',
        es='El programa de investigación en tres ejes: evaluación, aceptación, políticas.'),
    'recherche-items-llm': dict(
        fr='Des items générés par un LLM, jugés trois fois : alignement, exigence cognitive, qualité. Article en préparation.',
        en='Items generated by an LLM, judged three times: alignment, cognitive demand, quality. Article in preparation.',
        es='Ítems generados por un LLM, juzgados tres veces: alineación, exigencia cognitiva, calidad. Artículo en preparación.'),
    'recherche-essai-grappes': dict(
        fr='L’essai randomisé en grappes prévu : randomiser des écoles, pas des personnes.',
        en='The planned cluster-randomised trial: randomise schools, not people.',
        es='El ensayo aleatorizado por conglomerados previsto: aleatorizar escuelas, no personas.'),
    'acceptation-modele-tam': dict(
        fr='Le modèle d’acceptation de la technologie, d’après Davis (1989).',
        en='The technology acceptance model, after Davis (1989).',
        es='El modelo de aceptación de la tecnología, según Davis (1989).'),
    'methodes-recherche': dict(
        fr='Les méthodes mobilisées dans le programme.',
        en='The methods used across the programme.',
        es='Los métodos empleados en el programa.'),
    'politiques-niveaux': dict(
        fr='Quatre niveaux de textes, du principe national à la pratique de classe.',
        en='Four levels of texts, from national principle to classroom practice.',
        es='Cuatro niveles de textos, del principio nacional a la práctica de aula.'),
    'politiques-corpus-wpr': dict(
        fr='Un corpus de textes officiels, lu avec l’approche WPR (Bacchi, 2009). Article en préparation.',
        en='A corpus of official texts, read with the WPR approach (Bacchi, 2009). Article in preparation.',
        es='Un corpus de textos oficiales, leído con el enfoque WPR (Bacchi, 2009). Artículo en preparación.'),
    'ia-classe-quatre-questions': dict(
        fr='Quatre questions avant d’utiliser l’IA en classe. Proposition de l’auteur.',
        en='Four questions before using AI in class. The author’s proposal.',
        es='Cuatro preguntas antes de usar la IA en el aula. Propuesta del autor.'),
    'formations-formats': dict(
        fr='Trois formats de formation pour les établissements du canton de Vaud et de Suisse romande.',
        en='Three training formats for schools in the canton of Vaud and French-speaking Switzerland.',
        es='Tres formatos de formación para los centros del cantón de Vaud y de la Suiza francófona.'),
}

CC = dict(fr='CC BY 4.0', en='CC BY 4.0', es='CC BY 4.0')

for lang, P in PAGES.items():
    path = os.path.join(ROOT, P['file'])
    s = open(path, encoding='utf-8').read()

    # 1. lead
    old, new = LEAD[lang]
    assert s.count(old) == 1, (P['file'], 'lead')
    s = s.replace(old, new)

    # 2. gallery sections before </main>
    blocks = []
    for head, href, keys in SECTIONS[lang]:
        figs = []
        for k in keys:
            img = f'pablo-correa-prieto-{k}-{lang}.png'
            alt = ALTS[k][lang]
            cap = CAPTIONS[k][lang]
            figs.append(
                '<figure>\n'
                f'  <img src="/{img}" width="1800" height="945" loading="lazy" decoding="async" alt="{alt}">\n'
                f'  <figcaption>{cap}<br><small>© Pablo Correa Prieto, 2026 — <a href="{P["reuse"]}">{CC[lang]}</a></small></figcaption>\n'
                '</figure>')
        blocks.append(
            '<section class="sec gal">\n'
            f'<h2><a href="{href}">{head}</a></h2>\n'
            f'<p class="meta"><time datetime="2026-10-20">{P["date"]}</time></p>\n'
            + '\n'.join(figs) + '\n</section>')
    anchor = '</section>\n</main>'
    assert s.count(anchor) == 1, (P['file'], 'main')
    s = s.replace(anchor, '</section>\n' + '\n'.join(blocks) + '\n</main>')

    # 3. JSON-LD
    assert s.count('"numberOfItems": 15,') == 1
    s = s.replace('"numberOfItems": 15,', '"numberOfItems": 25,')
    order = [k for _, _, keys in SECTIONS[lang] for k in keys]
    items = []
    for i, k in enumerate(order, start=16):
        url = f'https://pablocorreaprieto.ch/pablo-correa-prieto-{k}-{lang}.png'
        items.append('     {\n      "@type": "ListItem",\n'
                     f'      "position": {i},\n'
                     '      "item": {\n'
                     f'       "@id": "{url}"\n'
                     '      }\n     }')
    li_anchor = '     }\n    ]\n   },\n   "hasPart": [\n'
    assert s.count(li_anchor) == 1, (P['file'], 'jsonld')
    parts = []
    for k in order:
        url = f'https://pablocorreaprieto.ch/pablo-correa-prieto-{k}-{lang}.png'
        parts.append(json.dumps({
            '@type': 'ImageObject', '@id': url, 'contentUrl': url, 'url': url,
            'width': 1800, 'height': 945,
            'caption': CAPTIONS[k][lang], 'description': ALTS[k][lang],
            'creator': {'@id': 'https://pablocorreaprieto.ch/#person'},
            'creditText': 'Pablo Correa Prieto',
            'copyrightNotice': '© 2026 Pablo Correa Prieto',
            'license': 'https://creativecommons.org/licenses/by/4.0/',
            'acquireLicensePage': f'https://pablocorreaprieto.ch{P["reuse"]}',
        }, ensure_ascii=False, indent=1).replace('\n', '\n    '))
    s = s.replace(li_anchor,
                  '     },\n' + ',\n'.join(items) + '\n    ]\n   },\n   "hasPart": [\n'
                  + '    ' + ',\n    '.join(parts) + ',\n')
    open(path, 'w', encoding='utf-8').write(s)
    print('updated', P['file'])
